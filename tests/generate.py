CONTROL_NUMBERS = tuple(hub.CONTROL_NUMBERS)


def render():
    title = lambda k: k.replace("_", " ")
    head = HEAD.format(top=options(""), **{b: options(b) for b in ("backup", "trace", "datalogger", "meter", "control")})
    out = head.splitlines()
    out += [f"    {k}_number: {title(k)}" for k in CONTROL_NUMBERS]
    out += [f"  {k}_number: {title(k)}" for k in settings.NUMBERS]
    out += [f"  {k}_switch: {title(k)}" for k in settings.SWITCHES]
    out += [f"  {k}_select: {title(k)}" for k in settings.SELECTS]
    # Named only to prove the relabel path; these are created without being named.
    for group in (telemetry.PRESETS, telemetry.DIAGNOSTICS, telemetry.HEALTH):
        out += [f"  {k}_sensor: {spec['name']}" for k, spec in group.items()]
    out += [
        "  registers:",
        "    - name: Parallel mode",
        "      address: 0xA02C",
        "      max_value: 7",
        "    - name: Grid overvoltage trip",
        "      address: 0xA04D",
        "      scale: 0.1",
        "      max_value: 300",
        "",
        "sensor:",
        "  - platform: aecc",
    ]
    out += ["    registers:", "      - name: Grid overvoltage trip",
            "        address: 0xA04D", "        scale: 0.1", "        interval: 60s"]
    out += [""]
    return "\n".join(out)


parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()

# The shape the mode select exists for: manual only, no meter and no second bus.
MANUAL_ONLY = """# Generated by tests/generate.py.
esphome:
  name: aecc-manual-only

esp32:
  board: esp32dev
  framework:
    type: esp-idf

external_components:
  - source:
      type: local
      path: ../components

uart:
  - id: bus_inverter
    tx_pin: GPIO32
    rx_pin: GPIO33
    baud_rate: 9600

aecc:
  id: nova
  uart_id: bus_inverter
  expose_all_settings: true
  datalogger:
    host: 192.0.2.10
  control:
    setpoint_number: Battery power
"""

FILES = {"all-keys.yaml": render, "manual-only.yaml": lambda: MANUAL_ONLY}

def missing_keys(rendered):
    """Keys the schema accepts but all-keys.yaml never names."""
    aecc = yaml.safe_load(rendered)["aecc"]
    absent = []
    for path, _, _ in KEYS:
        node = aecc
        for part in path.split("/"):
            node = node.get(part) if isinstance(node, dict) else None
        if node is None:
            absent.append(path)
    return absent


def undocumented():
    """Keys the schema accepts but the README never mentions."""
    readme = (HERE.parent / "README.md").read_text()
    settings_keys = set(settings.NUMBERS) | set(settings.SWITCHES) | set(settings.SELECTS)

    def mentioned(key):
        # A block reads `meter:`; a battery setting is listed by name under its suffix.
        base = key.rsplit("_", 1)[0]
        names = (key, base) if base in settings_keys else (key,)
        return any(f"`{n}`" in readme or f"`{n}:`" in readme for n in names)

    return sorted({p.rsplit("/", 1)[-1] for p, _, _ in KEYS} - {
        p.rsplit("/", 1)[-1] for p, _, _ in KEYS if mentioned(p.rsplit("/", 1)[-1])})


stale = []
for name, build in FILES.items():
    target = HERE / name
    want = build()
    if not args.check:
        target.write_text(want)
        continue
    if not target.exists() or target.read_text() != want:
        stale.append(name)
if stale:
    sys.exit(f"{', '.join('tests/' + s for s in stale)} stale; run tests/generate.py")

absent = missing_keys(render())
if absent:
    sys.exit(f"all-keys.yaml names no {', '.join(absent)}; the README calls it exhaustive")
missing = undocumented()
if missing:
    sys.exit(f"README.md never mentions {', '.join(missing)}")
