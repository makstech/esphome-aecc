#!/usr/bin/env python3
"""Regenerate all-keys.yaml, which names every key the component accepts.

Run with --check in CI: a key the schema accepts but all-keys.yaml or the README does not
name fails the build, rather than going quietly untested or undocumented.
"""

import argparse
import importlib
import importlib.machinery
import importlib.util
import pathlib
import sys
import types

import voluptuous as vol
import yaml

HERE = pathlib.Path(__file__).parent
# Imported as a package so the platforms' relative imports resolve; every entity list is
# read from source rather than restated here, or the check below would not see a new key.
sys.path.insert(0, str(HERE.parent))
sys.modules.setdefault("components", importlib.util.module_from_spec(
    importlib.machinery.ModuleSpec("components", None, is_package=True)
))
sys.modules["components"].__path__ = [str(HERE.parent / "components")]
hub = importlib.import_module("components.aecc")
settings = importlib.import_module("components.aecc.settings")
telemetry = importlib.import_module("components.aecc.telemetry")
import esphome.config_validation as cv  # noqa: E402
from esphome.const import CONF_NAME  # noqa: E402

TIME_UNITS = {"days", "hours", "minutes", "seconds", "milliseconds", "microseconds"}


def schemas(v, depth=0):
    """Every schema reachable through a validator: All/Any, lists, closures, typed maps."""
    if depth > 8:
        return []
    if isinstance(v, vol.Schema):
        if isinstance(v.schema, dict):
            keys = {str(k) for k in v.schema}
            return [] if keys and keys <= TIME_UNITS else [v]
        return schemas(v.schema, depth + 1)
    if isinstance(v, (vol.All, vol.Any)):
        return [s for x in v.validators for s in schemas(x, depth + 1)]
    if isinstance(v, (list, tuple)):
        return [s for x in v for s in schemas(x, depth + 1)]
    if isinstance(v, dict):
        return [s for x in v.values() for s in schemas(x, depth + 1)]
    if isinstance(v, types.FunctionType) and v.__closure__:
        out = []
        for cell in v.__closure__:
            try:
                out += schemas(cell.cell_contents, depth + 1)
            except ValueError:
                pass
        return out
    return []


def walk(schema, path=(), out=None):
    """(path, is_entity, default) for every key, descending into blocks but not entities."""
    out = [] if out is None else out
    for key, value in schema.schema.items():
        if isinstance(key, cv.GenerateID) or str(key) == "setup_priority":
            continue
        subs = schemas(value)
        entity = bool(subs) and CONF_NAME in {str(k) for k in subs[0].schema}
        default = key.default() if isinstance(key, vol.Optional) and key.default is not vol.UNDEFINED else None
        out.append(("/".join(path + (str(key),)), entity, default))
        if not entity:
            for sub in subs:
                walk(sub, path + (str(key),), out)
    return out


KEYS = walk(schemas(hub.CONFIG_SCHEMA)[0])
# A typed schema's discriminator is checked by a function, not declared as a key.
KEYS.insert([p for p, _, _ in KEYS].index("meter") + 1, ("meter/type", False, None))
BLOCKS = {p.rsplit("/", 1)[0] for p, _, _ in KEYS if "/" in p}
# Values for the options whose default would not make a working configuration.
FIXED = {
    "uart_id": "bus_inverter",
    "expose_all_settings": "true",
    "meter/type": "rs071",
    "meter/uart_id": "bus_meter",
    "datalogger/host": "192.0.2.10",
}


def options(block):
    """The block's plain options as YAML lines, each at its default unless FIXED says."""
    prefix, indent = (f"{block}/", "    ") if block else ("", "  ")
    lines = []
    for path, entity, default in KEYS:
        leaf = path[len(prefix):]
        if entity or not path.startswith(prefix) or "/" in leaf or path in BLOCKS:
            continue
        value = FIXED.get(path, default)
        if value is None:
            sys.exit(f"{path} has no default; give it a value in FIXED")
        if isinstance(value, bool):
            value = str(value).lower()
        lines.append(f"{indent}{leaf}: {value}")
    return "\n".join(lines)


